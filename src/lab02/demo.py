"""
Демонстрационный скрипт для класса ApartmentCollection.
Предметная область: Недвижимость.
"""

import sys
import os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from model import Apartment
from collection import ApartmentCollection


print("=" * 60)
print("ДЕМОНСТРАЦИЯ КОЛЛЕКЦИИ КВАРТИР")
print("=" * 60)

# ══════════════════════════════════════════════════════════════════════════
# 1. Создание коллекции
# ══════════════════════════════════════════════════════════════════════════
print("\n1. Создание пустой коллекции")
collection = ApartmentCollection()
print("   Коллекция создана")


# ══════════════════════════════════════════════════════════════════════════
# 2. Создание объектов квартир
# ══════════════════════════════════════════════════════════════════════════
print("\n2. Создание объектов квартир")

apt1 = Apartment(
    address="ул. Ленина, д. 10, кв. 5",
    area=54.5,
    price=35000,
    rooms=2,
)
print(f"   Создана квартира 1: {apt1.address}")

apt2 = Apartment(
    address="пр. Мира, д. 3, кв. 12",
    area=80.0,
    price=55000,
    rooms=3,
)
print(f"   Создана квартира 2: {apt2.address}")

apt3 = Apartment(
    address="ул. Пушкина, д. 7, кв. 22",
    area=42.0,
    price=28000,
    rooms=1,
)
print(f"   Создана квартира 3: {apt3.address}")


# ══════════════════════════════════════════════════════════════════════════
# 3. Добавление квартир в коллекцию (метод add)
# ══════════════════════════════════════════════════════════════════════════
print("\n3. Добавление квартир в коллекцию")

collection.add(apt1)
print(f"   Добавлена: {apt1.address}")

collection.add(apt2)
print(f"   Добавлена: {apt2.address}")

collection.add(apt3)
print(f"   Добавлена: {apt3.address}")


# ══════════════════════════════════════════════════════════════════════════
# 4. Получение всех квартир (метод get_all)
# ══════════════════════════════════════════════════════════════════════════
print("\n4. Получение всех квартир из коллекции")

all_apartments = collection.get_all()
print(f"   Всего квартир в коллекции: {len(all_apartments)}")

print("\n   Список квартир:")
for i, apt in enumerate(all_apartments, 1):
    print(f"   {i}. {apt.address} - {apt.area} м², {apt.price} руб.")


# ══════════════════════════════════════════════════════════════════════════
# 5. Удаление квартиры (метод remove)
# ══════════════════════════════════════════════════════════════════════════
print("\n5. Удаление квартиры из коллекции")
print(f"   Удаляем: {apt2.address}")

collection.remove(apt2)
print("   Квартира удалена")

all_apartments = collection.get_all()
print(f"   Осталось квартир: {len(all_apartments)}")


# ══════════════════════════════════════════════════════════════════════════
# 6. Проверка типов (попытка добавить неправильный объект)
# ══════════════════════════════════════════════════════════════════════════
print("\n6. Проверка типов при добавлении")
print("   Попытка добавить строку вместо объекта Apartment:")

try:
    collection.add("это не квартира")
    print("   ОШИБКА: объект был добавлен!")
except TypeError as e:
    print(f"   Корректно: {e}")


# ══════════════════════════════════════════════════════════════════════════
# 7. Попытка удалить несуществующий объект
# ══════════════════════════════════════════════════════════════════════════
print("\n7. Попытка удалить объект, которого нет в коллекции")

apt_new = Apartment(
    address="ул. Гоголя, д. 1, кв. 1",
    area=50.0,
    price=30000,
    rooms=2,
)
print(f"   Попытка удалить: {apt_new.address}")

try:
    collection.remove(apt_new)
    print("   ОШИБКА: объект был удалён!")
except ValueError as e:
    print(f"   Корректно: {e}")


# ══════════════════════════════════════════════════════════════════════════
# ИТОГ
# ══════════════════════════════════════════════════════════════════════════
print("\n" + "=" * 60)
print("ИТОГ")
print("=" * 60)

final_list = collection.get_all()
print(f"\nКвартир в коллекции: {len(final_list)}")
print("\nФинальный список:")
for i, apt in enumerate(final_list, 1):
    print(f"{i}. {apt.address}")

print("\nДемонстрация завершена.")